/*
44. Нулевые слайсы
Нулевым значением слайса является nil.

Нулевой слайс имеет длину и вместимость 0 и не имеет базового массива.

Дополнительно к официальной теории:
  - Нулевой (nil) слайс отличается от пустого (empty) слайса: у обоих len == 0 и
    cap == 0, но nil-слайс не указывает ни на какой базовый массив, а []int{}
    (или make([]int, 0)) указывает на существующий (пустой) массив. Сравнение
    s == nil истинно только для настоящего nil-слайса.
  - Слайсы (в отличие от массивов) нельзя сравнивать оператором ==/!= между
    собой — компилятор это запретит. Единственное разрешённое сравнение слайса —
    с литералом nil.
  - К nil-слайсу можно безопасно применять len(), cap() и range — паники не будет,
    цикл range просто не выполнит ни одной итерации.
  - К nil-слайсу можно применять append() — Go выделит новый базовый массив
    "на лету", и после первого append слайс перестанет быть nil.
  - Обращение по индексу к nil-слайсу (s[0]) вызовет панику "index out of range",
    так как элементов нет — это отличает nil-слайс от nil-указателя, но по духу
    паника аналогична обращению за пределы длины любого пустого слайса.
*/

package main

import "fmt"

func printSliceInfo[T any](name string, s []T) {
	fmt.Printf("%s: len=%d cap=%d значения=%v isNil=%t\n", name, len(s), cap(s), s, s == nil)
}

func makeTheory() {
	var s []int
	printSliceInfo("s", s)

	if s == nil {
		fmt.Println("s пуст!")
	}

	empty := []int{}
	printSliceInfo("empty", empty)

	s = append(s, 1)
	printSliceInfo("s после append", s)
}

func isEmpty[T any](s []T) bool {
	if s == nil || 0 == len(s) {
		return true
	}
	return false
}

