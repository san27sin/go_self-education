/*
28. Оператор switch
Оператор switch — это более короткий способ записи последовательности операторов if-else. Он выполняет первый case, значение которого совпадает с условием.

Switch в Go похож на аналогичные операторы в C, C++, Java, JavaScript и PHP, но с отличием: Go выполняет только выбранный case, а не все последующие. Фактически, инструкция break, которая требуется в конце каждого case в других языках, в Go добавляется автоматически.

Еще одно важное отличие: в Go значения в case не обязаны быть константами, а также не обязаны быть целыми числами.

Домашнее задание
  Классификатор времени суток

  Напиши программу, которая определяет время суток по введённому часу (0–23) и выводит соответствующее сообщение.

  Требования:

  1. Используй switch без условия (switch без выражения работает как цепочка if-else)
  2. Определи 4 периода дня:
    - 0–5 → "Ночь"
    - 6–11 → "Утро"
    - 12–17 → "День"
    - 18–23 → "Вечер"
  3. Если введено число вне диапазона 0–23 — выведи ошибку
  4. В каждом case используй несколько значений через запятую или диапазон через несколько case-веток с fallthrough (на выбор)
*/

package main

import (
	"fmt"
	"runtime"
)

func completeLesson() {
	fmt.Print("Go runs on ")
	switch os := runtime.GOOS; os {
	case "darwin":
		fmt.Println("macOS.")
	case "linux":
		fmt.Println("Linux.")
	default:
		// freebsd, openbsd,
		// plan9, windows...
		fmt.Printf("%s.\n", os)
	}
}

func completeHW(hours int) {
	switch hours {
	case 0, 1, 2, 3, 4, 5:
		fmt.Println("Ночь")
	case 6, 7, 8, 9, 10, 11:
		fmt.Println("Утро")
	case 12, 13, 14, 15, 16, 17:
		fmt.Println("День")
	case 18, 19, 20, 21, 22, 23:
		fmt.Println("Вечер")
	default:
		fmt.Println("Столько часов не бывает...")
	}
}

func main() {
	// completeLesson()
	completeHW(12)
}
