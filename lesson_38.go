/*
38. Массивы
Тип [n]T представляет собой массив из n значений типа T.

Выражение
var a [10]int
объявляет переменную a как массив из десяти целых чисел.

Длина массива является частью его типа, поэтому массивы нельзя изменять.
Это может показаться ограничением, но не беспокойтесь: в Go предусмотрен удобный способ работы с массивами.


1. Объявление
var a [10]int        // массив из 10 int, все элементы = 0 (zero value)
var b [5]string       // массив из 5 string, все элементы = ""
Тип массива — это [n]T, где n — длина. Важно: [5]int и [10]int — это разные типы, их нельзя присвоить друг другу и нельзя передать функции, ожидающей другую длину.

2. Длина — часть типа → массивы не растут
a := [3]int{1, 2, 3}
a[3] = 4 // ошибка компиляции: index out of range
Длину нельзя менять после объявления — в этом и смысл фразы из твоего конспекта "массивы нельзя изменять" (точнее — нельзя менять их размер, значения менять
можно).

3. Литералы массива
a := [5]int{1, 2, 3, 4, 5}
b := [...]int{1, 2, 3}    осчитает длину (тут будет[3]int)
c := [5]int{2: 100}       явно: c = [0 0 100 0 0]

4. Массивы копируются по значению
Это ключевое отличие от мн
a := [3]int{1, 2, 3}
b := a          // b — это ПОЛНАЯ КОПИЯ a
b[0] = 100
fmt.Println(a)  // [1 2 3]
Так же при передаче в функцию — массив копируется целиком:
func modify(arr [3]int) {
    arr[0] = 999 // меняет только копию
}
Именно из-за этого «неудобства» в Go обычно используют слайсы ([]T) вместо массивов — но это уже следующая тема, до неё Go Tour как раз и подводит.

5. Сравнение
Массивы можно сравнивать оператором ==, если тип элементов сравнимый:
a := [3]int{1, 2, 3}
b := [3]int{1, 2, 3}
fmt.Println(a == b) // tru

6. Многомерные массивы
var grid [2][3]int // 2 строки, 3 столбца

Домашнее задание
1. Объяви массив var primes [6]int и вручную заполни его первыми шестью простыми числами: 2, 3, 5, 7, 11, 13.
2. Выведи весь массив и его длину (len(primes)).
3. Создай копию массива primesCopy := primes, измени в копии первый элемент на -1 и выведи оба массива — убедись, что оригинал не изменился (это как раз демонстрация копирования по значению).
4. Напиши цикл for i, v := range primes, который посчитает и выведет сумму всех элементов массива.
*/

package main

import "fmt"

func main() {
	// №1
	var primes [6]int
	primes[0] = 2
	primes[1] = 3
	primes[2] = 5
	primes[3] = 7
	primes[4] = 11
	primes[5] = 13

	// №2
	fmt.Println("массив: ", primes)
	fmt.Println("длина массива: ", len(primes))

	// №3
	copyArray := primes
	copyArray[0] = -1
	fmt.Println("оригинальный массив", primes)
	fmt.Println("копия массива", copyArray)

	// №4
	sum := 0
	for i, v := range primes {
		_ = i
		sum += v
	}
	fmt.Println(sum)
}
