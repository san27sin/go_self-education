package lesson81

/*
81. Задание: rot13Reader
Распространённым шаблоном является io.Reader,
который оборачивает другой io.Reader,
modificруя поток данных тем или иным способом.

Например,
функция gzip.NewReader принимает io.Reader (поток сжатых данных) и возвращает *gzip.Reader,
который также реализует io.Reader (поток распакованных данных).

Реализуйте rot13Reader,
который реализует io.Reader и читает из io.Reader,
modificруя поток путём применения шифра подстановки rot13 ко всем буквенным символам.

Тип rot13Reader предоставлен вам. Сделайте его io.Reader, реализовав его метод Read.
*/

import (
	"fmt"     // для печати перевода строки в конце
	"io"      // интерфейс io.Reader и функция io.Copy
	"os"      // os.Stdout — стандартный вывод (как process.stdout в Node)
	"strings" // strings.NewReader — делает io.Reader из обычной строки
)

// rot13Reader — "обёртка" над другим Reader'ом.
// Аналогия с JS: это как Transform-стрим в Node — читаем из исходного потока
// и отдаём наружу уже изменённые байты.
type rot13Reader struct {
	r io.Reader // исходный поток, из которого мы берём зашифрованные байты
}

// rot13 сдвигает одну латинскую букву на 13 позиций по алфавиту.
// Т.к. в алфавите 26 букв, применение rot13 дважды возвращает исходную букву,
// поэтому шифрование и расшифровка — одна и та же операция.
func rot13(c byte) byte {
	switch {
	case c >= 'a' && c <= 'z': // строчная буква
		// c - 'a'      -> номер буквы в алфавите (0..25)
		// + 13         -> сдвигаем на 13
		// % 26         -> "заворачиваем" за 'z' обратно к 'a'
		// + 'a'        -> превращаем номер обратно в код символа
		return (c-'a'+13)%26 + 'a'
	case c >= 'A' && c <= 'Z': // заглавная буква — то же самое, но от 'A'
		return (c-'A'+13)%26 + 'A'
	default: // пробелы, знаки препинания, цифры — не трогаем
		return c
	}
}

// Read — единственный метод интерфейса io.Reader.
// Контракт: заполнить срез b данными и вернуть, сколько байт записано (n)
// и ошибку (io.EOF, когда данные закончились).
func (rr rot13Reader) Read(b []byte) (n int, err error) {
	// 1. Сначала читаем данные из ВНУТРЕННЕГО ридера прямо в тот же буфер b.
	//    n — сколько байт реально прочитано (может быть меньше len(b)!).
	n, err = rr.r.Read(b)

	// 2. Проходим только по реально прочитанным байтам: b[:n], а не весь b.
	//    Хвост b после n — мусор, его трогать нельзя.
	for i := 0; i < n; i++ {
		b[i] = rot13(b[i]) // заменяем каждый байт его rot13-версией
	}

	// 3. Возвращаем столько же байт и ту же ошибку, что дал внутренний ридер.
	//    Когда строка закончится, внутренний ридер вернёт io.EOF,
	//    мы его "пробросим" наружу, и io.Copy поймёт, что пора остановиться.
	return n, err
}

func Run() {
	// Создаём Reader из зашифрованной строки
	s := strings.NewReader("Lbh penpxrq gur pbqr!")

	// Оборачиваем его в наш rot13Reader
	r := rot13Reader{s}

	// io.Copy в цикле вызывает r.Read(...) и пишет результат в os.Stdout,
	// пока Read не вернёт io.EOF. Нам ничего не нужно делать вручную.
	io.Copy(os.Stdout, &r)

	fmt.Println() // перевод строки после результата
}
