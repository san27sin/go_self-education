/*
79. Ридеры (Readers)
Пакет io определяет интерфейс io.Reader, который представляет конечную точку для чтения потока данных.

Стандартная библиотека Go содержит множество реализаций этого интерфейса, включая файлы, сетевые соединения, компрессоры, 
шифраторы и другие.

Интерфейс io.Reader имеет метод Read:

func (T) Read(b []byte) (n int, err error)

Read заполняет предоставленный байтовый срез (b) данными и возвращает количество записанных байт (n) и значение ошибки (err). 
Он возвращает ошибку io.EOF, когда поток данных заканчивается.

Пример кода создает strings.Reader и потребляет его вывод по 8 байт за раз.


*/

// Пакет lesson79 — код урока 79, запускается из main.go через Run()
package lesson79

import (
	"fmt"     // форматированный вывод (Printf)
	"io"      // интерфейс io.Reader и значение ошибки io.EOF
	"strings" // strings.NewReader — Reader поверх обычной строки
)

// Run — запускает пример урока
func Run() {
	// Создаём Reader, который будет отдавать байты строки "Hello, Reader!" (14 байт)
	r := strings.NewReader("Hello, Reader!")

	// Создаём буфер на 8 байт — за один вызов Read получим не больше 8 байт
	b := make([]byte, 8)
	// Бесконечный цикл: читаем, пока не дойдём до конца данных
	for {
		// Read заполняет b очередной порцией данных:
		// n — сколько байт реально записано, err — ошибка (io.EOF в конце потока)
		n, err := r.Read(b)
		// Печатаем n, err и весь буфер целиком (включая старые байты от прошлых чтений)
		fmt.Printf("n = %v err = %v b = %v\n", n, err, b)
		// Печатаем только реально прочитанную часть b[:n]; %q выводит её как строку в кавычках
		fmt.Printf("b[:n] = %q\n", b[:n])
		// Если данные закончились — выходим из цикла
		if err == io.EOF {
			break
		}
	}
}
