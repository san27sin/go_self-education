package lessons

import "fmt"

func sum(s []int, c chan int) {
	sum := 0
	for _, v := range s {
		sum += v
	}
	c <- sum // send sum to c
}

func makeTheory() {
	s := []int{7, 2, 8, -9, 4, 0}

	c := make(chan int)
	go sum(s[:len(s)/2], c)
	go sum(s[len(s)/2:], c)
	x, y := <-c, <-c // receive from c

	fmt.Println(x, y, x+y)
}

func makeHomework() {
	words := []string{"go", "channel", "goroutine", "tour"}
	channels := make(chan int, 4)
	for _, w := range words {
		go func() {
			channels <- len(w)
		}()
	}
	sum := 0
	for range len(channels) {
		sum += <-channels
	}
	fmt.Println(sum)
}

