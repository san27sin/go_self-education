/*
31. Defer
Оператор defer откладывает выполнение функции до момента выхода из окружающей функции.

Аргументы отложенного вызова вычисляются немедленно, но сам вызов функции не происходит до возврата из окружающей функции.

Задание: Логгер вызовов функций

Напиши функцию divide(a, b float64) float64, которая делит a на b.

С помощью defer реализуй логгер, который при каждом вызове divide выводит в консоль:

calling divide(10, 2)
divide(10, 2) = 5

calling divide(9, 3)
divide(9, 3) = 3

Логгер должен работать через defer, а не через обычный вызов в конце функции.

---
Подсказка: defer может вызывать анонимную функцию, которая читает возвращаемое значение — но для этого потребуется именованное возвращаемое значение.

func divide(a, b float64) (result float64) {
    // твой код
}

Попробуй реализовать — покажи что получится, разберём вместе.
*/

package main

import "fmt"

func divide(a, b float64) (result float64) {
	defer func() {
		fmt.Printf("divide(%v, %v) = %v\n", a, b, result)
	}()
	defer fmt.Printf("calling divide(%v, %v)\n", a, b)
	result = a / b
	return
}

func main() {
	divide(10, 2)
	divide(9, 3)
}