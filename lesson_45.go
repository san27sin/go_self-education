/*
45. Создание слайса с помощью make
Слайсы можно создавать встроенной функцией make; именно так создаются
динамически размеряемые массивы.

Функция make выделяет обнулённый массив и возвращает слайс, ссылающийся на этот массив:

  a := make([]int, 5)  // len(a)=5

Чтобы задать вместимость, передайте третий аргумент в make:

  b := make([]int, 0, 5) // len(b)=0, cap(b)=5

  b = b[:cap(b)] // len(b)=5, cap(b)=5
  b = b[1:]      // len(b)=4, cap(b)=4

Дополнительно к официальной теории:
  - make([]T, len) — это сокращение для make([]T, len, len): вместимость по
    умолчанию равна длине.
  - В отличие от var s []T (nil-слайс), make всегда сразу выделяет базовый
    массив — даже make([]T, 0) вернёт не-nil слайс с cap == 0.
  - Элементы, выделенные через make, всегда обнулены (zero value типа T),
    как и элементы обычного массива.
  - make — единственный способ задать вместимость больше длины напрямую;
    через слайс-литерал []T{...} вместимость всегда равна длине литерала.
  - Если передать в make отрицательную длину/вместимость либо len > cap,
    компилятор/рантайм даст ошибку ("makeslice: len out of range" и т.п.).
*/

package main

import (
	"fmt"
	"math/rand"
)

func printSlice123(name string, s []int) {
	fmt.Printf("%s: len=%d cap=%d %v\n", name, len(s), cap(s), s)
}

// Задание:
//  1. Создайте слайс чисел c := make([]int, 3) и выведите его через printSlice.
//     Объясните в комментарии, чему равны его элементы и почему.
//  2. Создайте слайс d := make([]int, 2, 6) (len=2, cap=6) и выведите его.
//  3. С помощью реслайсинга (без append) увеличьте длину d до максимально
//     возможной вместимости и выведите после каждого шага — понаблюдайте,
//     что новые элементы (за пределами исходной длины 2) появляются со
//     значением по умолчанию (0), а не мусором.
//  4. Заполните d произвольными числами через присваивание по индексу
//     (d[i] = ...) и добавьте ещё один элемент через append — проверьте,
//     остался ли базовый массив тем же (сравните адреса через &d[0] до
//     и после append, когда есть свободная вместимость, и когда её нет).

func main() {
	// #1
	test := make([]int, 3)
	printSlice123("c = ", test) // равны нулям потому что это как дефолтные значения для инициализации
	// #2
	dob := make([]int, 2, 6)
	printSlice123("list", dob)
	// #3
	for n := len(dob); n <= cap(dob); n++ {
		dob = dob[:n]
		printSlice123("dob (ресайслинг) = ", dob)
	}
	// #4
	var pointer_1 *int
	for index := 0; index < len(dob); index++ {
		dob[index] = rand.Intn(50)
		if (index == 0) {
			pointer_1 = &dob[index]
		}
	}
	dob = append(dob, 999)
	pointer_2 := &dob[0]
	fmt.Println(pointer_1 == pointer_2)
}
