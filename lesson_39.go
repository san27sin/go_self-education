/*
39. Слайсы
Массив имеет фиксированный размер. Слайс, в свою очередь, представляет собой динамически изменяемое гибкое представление элементов массива.
На практике слайсы встречаются гораздо чаще массивов.

Тип []T является слайсом с элементами типа T.

Слайс формируется путем указания двух индексов - нижней и верхней границы, разделенных двоеточием:

1
a[low : high]
Это задает полуоткрытый диапазон, который включает первый элемент, но исключает последний.

Следующее выражение создает слайс, включающий элементы с 1 по 3 массива a:

1
a[1:4]

*/

package main

import "fmt"

// reverse разворачивает слайс на месте, не создавая новый слайс/массив.
func reverse(s []int) {
	i, j := 0, len(s)-1
	for i < j {
		s[i], s[j] = s[j], s[i]
		i++
		j--
	}
}

func main() {
	arr := [6]int{10, 20, 30, 40, 50, 60}
	s := arr[1:4]
	fmt.Println("s = ", s)
	fmt.Println("len = ", len(s))
	fmt.Println("cap = ", cap(s))

	s[0] = 999
	// arr[1] тоже стал 999: s и arr делят один и тот же базовый массив,
	// s[0] - это то же место в памяти, что и arr[1]
	fmt.Println("arr = ", arr)
	fmt.Println("arr[1] = ", arr[1])

	for i := 0; i < 3; i++ {
		fmt.Println("\n")
		fmt.Println(i+1, " - случай")
		s = append(s, 111)
		fmt.Println("s = ", s)
		fmt.Println("len = ", len(s))
		fmt.Println("cap = ", cap(s))
		fmt.Println("arr = ", arr)
		// пока len(s) < cap(s), append дописывает в тот же arr - arr меняется.
		// как только len(s) == cap(s) (случай 3), места не хватает,
		// Go выделяет новый массив большего размера - arr дальше уже не меняется.
	}

	fmt.Println("\nreverse:")
	fmt.Println("до:", s)
	reverse(s)
	fmt.Println("после:", s)
}
